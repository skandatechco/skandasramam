/**
 * Builds docs/launch/CATALOGUE_REPORT.md by applying the migrations and the seed to
 * an in-memory PGlite database (never a real one) and reading the result back.
 *   npx tsx supabase/scripts/catalogue-report.ts
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { resolveDestination } from "../../shared/poojaPages";

import { fileURLToPath } from "node:url";
const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const db = new PGlite();

async function main() {
  await db.exec(`
    create role anon nologin; create role authenticated nologin; create role service_role nologin bypassrls;
    create schema auth; create table auth.users (id uuid primary key, email text);
    create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
    create function auth.jwt() returns jsonb language sql stable as $$ select '{}'::jsonb $$;
  `);
  for (const f of readdirSync(join(root, "migrations")).sort())
    await db.exec(readFileSync(join(root, "migrations", f), "utf8"));
  await db.exec(readFileSync(join(root, "seed", "poojas.seed.sql"), "utf8"));

  const rows = (
    await db.query<any>(`
    select p.slug, p.name, p.type, p.amount_inr::float8 amt,
      (select string_agg(coalesce(r.start_time::text,'-') || ' ' || r.recurrence, '; ') from public.recurring_pooja_schedule r where r.pooja_id = p.id) rec,
      (select string_agg(
          'tithi=' || coalesce(array_to_string(x.tithis, '/'), '*') ||
          ' paksha=' || coalesce(x.paksha, '*') ||
          ' nakshatra=' || coalesce(array_to_string(x.nakshatras, '/'), '*') ||
          ' time=' || coalesce(x.start_time::text, 'none'), '; ')
         from public.panchangam_pooja_rules x where x.pooja_id = p.id) pan
    from public.poojas p order by (p.type = 'special'), p.type, p.name`)
  ).rows;

  const sched = (r: any) =>
    r.rec
      ? `daily, ${r.rec.split(" ")[0].slice(0, 5)}`
      : r.pan
        ? r.pan.replace(/:00(?=$|;)/g, "")
        : "no dates entered yet (temple to schedule)";
  const lines = rows.map(
    (r) =>
      `| ${r.name} | \`${r.slug}\` | ${r.type} | ₹${r.amt} | ${sched(r)} | ${resolveDestination(r.slug) ?? "NONE"} |`,
  );
  const by = (t: string) => rows.filter((r) => r.type === t).length;
  const md = `# Catalogue verification report

Generated by \`npx tsx supabase/scripts/catalogue-report.ts\` from the real migrations and
\`supabase/seed/poojas.seed.sql\`, applied to an **in-memory** database. Nothing was run
against Supabase. Re-run it after any change to the seed.

## Summary
- Poojas: **${rows.length}** (daily ${by("daily")}, Panchangam-based ${by("panchangam")}, special ${by("special")})
- Standard rates: ${rows.filter((r) => r.amt === 100).length} at ₹100 (regular), ${rows.filter((r) => r.amt === 1000).length} at ₹1,000 (special)
- Every pooja resolves to a public booking page: ${rows.every((r) => resolveDestination(r.slug)) ? "yes" : "NO"}
- Annadanam / Daily Annadhanam: excluded (donation flow, not bookable, no price)
- No timings or festival dates are invented: start times are those printed on the website's Regular Poojas page.

## Poojas
| Pooja | Slug | Type | Rate | Schedule | Booking page |
|---|---|---|---|---|---|
${lines.join("\n")}

## Temple decisions (confirmed 2026-11-15)
1. Sankata Hara Chaturthi and Krishna Paksha Ashtami: Krishna paksha only.
2. Tamil Month First Saturday: ₹100, special-type, dates entered manually (needs the Tamil solar month, not in pooja_days).
3. Navavarna Pooja (regular) and Nava Varna Pooja (special): separate offerings.
4. Prathiyankara Sarabha Sulini Homam (regular) and Prathyangira Sarabha Soolini Koti Homam (special): separate offerings.
5. Annadanam: a donation flow, outside fixed-price bookings.

## Still open
- Navavarna Pooja has no start time (none is published).
- The special poojas and Tamil Month First Saturday have **no dates** until the temple adds them (Admin > Poojas & schedules).
- Festival poojas are defined one by one in Admin > Festival poojas, each with its own rate.
`;
  mkdirSync(join(root, "..", "docs", "launch"), { recursive: true });
  writeFileSync(join(root, "..", "docs", "launch", "CATALOGUE_REPORT.md"), md);
  console.log(`wrote report for ${rows.length} poojas`);
}
main();
